import "dotenv/config";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { chromium, expect, type Page } from "@playwright/test";
import { and, eq, inArray } from "drizzle-orm";
import { db, pool } from "../src/db";
import { lessonPackages, lessons, sessions, teacherProfiles, transactions, users } from "../src/db/schema";
import { hashPassword } from "../src/lib/auth";
import { ensureSeed } from "../src/lib/seed";
const base=process.env.TEST_URL||"http://localhost:3000";
async function run(){
  await ensureSeed();
  const ids:number[]=[];
  const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
  const contexts=[];
  try{
    const stamp=randomUUID();
    const password="BrowserTest2026!";
    const [student]=await db.insert(users).values({name:"Browser Learner",email:`student-${stamp}@test.invalid`,passwordHash:hashPassword(password),role:"student",balance:100000,avatar:"https://api.dicebear.com/9.x/notionists/svg?seed=learner"}).returning();ids.push(student.id);
    const [tutor]=await db.insert(users).values({name:"Browser Tutor",email:`teacher-${stamp}@test.invalid`,passwordHash:hashPassword(password),role:"teacher",avatar:"https://randomuser.me/api/portraits/women/44.jpg"}).returning();ids.push(tutor.id);
    await db.insert(teacherProfiles).values({userId:tutor.id,price:2750,headline:"One-to-one conversation and exam prep",speaks:"English, Mandarin",tags:"Conversation,IELTS",certified:true,startHour:0,endHour:24,tzOffset:0,platformDefault:"zoom"});
    const learnerContext=await browser.newContext({viewport:{width:1440,height:1100}}),teacherContext=await browser.newContext({viewport:{width:1440,height:1000}});
    contexts.push(learnerContext,teacherContext);
    await learnerContext.route("https://meet.jit.si/**",route=>route.abort());await teacherContext.route("https://meet.jit.si/**",route=>route.abort());
    const learner=await learnerContext.newPage(),teacher=await teacherContext.newPage();
    const login=async(page:Page,email:string)=>{await page.goto(`${base}/login`,{waitUntil:"networkidle"});await page.locator('input[name="email"]').fill(email);await page.locator('input[name="password"]').fill(password);await page.getByRole("button",{name:"Log in",exact:true}).click();await page.waitForURL(/dashboard/,{timeout:30000});};
    await login(learner,student.email);
    await learner.goto(`${base}/dashboard?tab=packages&teacher=${tutor.id}`);
    await expect(learner.getByRole("heading",{name:"More lessons. More progress."})).toBeVisible();
    await expect(learner.getByRole("button",{name:/US\$26\.13/})).toBeVisible();
    await learner.getByRole("button",{name:"25 mins",exact:true}).click();
    await expect(learner.getByRole("button",{name:/US\$13\.06/})).toBeVisible();
    await learner.getByRole("button",{name:"50 mins",exact:true}).click();
    await learner.getByRole("button",{name:/5 lessons · 50 mins/}).click();
    await learner.screenshot({path:"/tmp/lingorain-packages-desktop.png",fullPage:true});
    console.log("PASS desktop duration tabs and screenshot-matching discounted prices");
    await learner.getByRole("button",{name:"Get this package",exact:true}).click();
    const dialog=learner.getByRole("dialog");
    await expect(dialog).toBeVisible();await expect(dialog.getByText("US$130.65",{exact:true})).toBeVisible();
    await dialog.getByRole("button",{name:"Confirm purchase",exact:true}).click();
    await expect(dialog.getByRole("heading",{name:/Your package is ready/})).toBeVisible({timeout:30000});
    await dialog.getByRole("button",{name:"Close",exact:true}).last().click();
    await learner.getByRole("button",{name:/My packages/}).click();
    await expect(learner.getByRole("heading",{name:"Browser Tutor",exact:true})).toBeVisible();
    const [pack]=await db.select().from(lessonPackages).where(eq(lessonPackages.studentId,student.id));
    assert.equal(pack.remainingLessons,5);assert.equal(pack.totalPrice,13065);
    const [paid]=await db.select().from(users).where(eq(users.id,student.id));assert.equal(paid.balance,86935);
    console.log("PASS wallet checkout, confirmation dialog and purchased-package inventory");
    await learner.getByRole("link",{name:"Book from package",exact:true}).click();
    await learner.getByRole("button",{name:/^\d{2}:\d{2}$/}).first().click();
    await learner.getByRole("button",{name:"Book from package",exact:true}).click();
    await learner.waitForURL(/tab=lessons/,{timeout:30000});
    await expect(learner.getByText("Tutor will choose the classroom",{exact:true})).toBeVisible();
    const [lesson]=await db.select().from(lessons).where(eq(lessons.studentId,student.id));
    assert.equal(lesson.platform,"undecided");assert.equal(lesson.packageId,pack.id);
    assert.equal((await db.select().from(lessonPackages).where(eq(lessonPackages.id,pack.id)))[0].remainingLessons,4);
    assert.equal((await db.select().from(users).where(eq(users.id,student.id)))[0].balance,86935);
    await learner.goto(`${base}/classroom/${lesson.id}`);
    await expect(learner.getByRole("heading",{name:"Your classroom is being prepared",exact:true})).toBeVisible();
    await expect(learner.getByRole("button",{name:"Save & notify student",exact:true})).toHaveCount(0);
    console.log("PASS credit booking, no preselected platform and student cannot select a classroom");
    await login(teacher,tutor.email);
    await teacher.goto(`${base}/dashboard?tab=lessons`);
    await teacher.getByRole("button",{name:"Confirm",exact:true}).click();
    await expect.poll(async()=> (await db.select().from(lessons).where(eq(lessons.id,lesson.id)))[0].status).toBe("confirmed");
    await db.update(lessons).set({startAt:new Date(Date.now()-5*60_000)}).where(eq(lessons.id,lesson.id));
    await teacher.goto(`${base}/classroom/${lesson.id}`);
    await teacher.getByRole("button",{name:/Google Meet/,exact:false}).click();
    await expect(teacher.locator('input[name="meetingUrl"]')).toBeVisible();
    await teacher.locator('input[name="meetingUrl"]').fill("https://meet.google.com/abc-defg-hij");
    await teacher.getByRole("button",{name:"Save & notify student",exact:true}).click();
    await expect(teacher.getByRole("link",{name:"Join classroom",exact:true})).toHaveAttribute("href","https://meet.google.com/abc-defg-hij",{timeout:15000});
    await learner.bringToFront();
    await expect(learner.getByRole("link",{name:"Join classroom",exact:true})).toHaveAttribute("href","https://meet.google.com/abc-defg-hij",{timeout:15000});
    console.log("PASS tutor chooses Meet after booking; student page updates without reload");
    await teacher.getByRole("button",{name:/Zoom/,exact:false}).click();
    await teacher.locator('input[name="meetingUrl"]').fill("https://us02web.zoom.us/j/123456789?pwd=example");
    await teacher.getByRole("button",{name:"Save & notify student",exact:true}).click();
    await learner.bringToFront();
    await expect(learner.getByRole("link",{name:"Join classroom",exact:true})).toHaveAttribute("href",/zoom.us/,{timeout:15000});
    await learner.getByRole("button",{name:"Ask tutor to switch",exact:true}).click();
    await expect(learner.getByText(/Your tutor has been notified/)).toBeVisible();
    await teacher.bringToFront();
    await expect(teacher.getByText(/Your student reported a connection problem/)).toBeVisible({timeout:15000});
    await teacher.getByRole("button",{name:/Lingo Room/,exact:false}).click();
    await teacher.getByRole("button",{name:"Save & notify student",exact:true}).click();
    await learner.bringToFront();
    await expect(learner.locator('iframe[title="Lingo Room"]')).toHaveCount(1,{timeout:15000});
    await expect(learner.getByText(/Your tutor changed the classroom/)).toBeVisible();
    console.log("PASS live Meet → Zoom → Lingo failover and student problem request");
    assert.equal((await db.select().from(users).where(eq(users.id,student.id)))[0].balance,86935);
    assert.equal((await db.select().from(lessonPackages).where(eq(lessonPackages.id,pack.id)))[0].remainingLessons,4);
    const anonymous=await browser.newContext();contexts.push(anonymous);
    assert.equal((await anonymous.request.get(`${base}/api/lessons/${lesson.id}/room`)).status(),401);
    console.log("PASS switching has no extra charge and anonymous room API access is denied");
    await learner.setViewportSize({width:390,height:844});
    await learner.goto(`${base}/dashboard?tab=packages&teacher=${tutor.id}`);
    await expect(learner.getByRole("heading",{name:"More lessons. More progress."})).toBeVisible();
    const sizes=await learner.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
    await learner.screenshot({path:"/tmp/lingorain-packages-mobile.png",fullPage:true});
    if(sizes.scroll>sizes.width+1)console.error(await learner.evaluate(()=>[...document.querySelectorAll("body *")].map(el=>({tag:el.tagName,cls:el.className,left:el.getBoundingClientRect().left,right:el.getBoundingClientRect().right})).filter(x=>x.right>innerWidth+2||x.left< -2).slice(0,12)));
    assert.ok(sizes.scroll<=sizes.width+1,`Mobile overflow: ${JSON.stringify(sizes)}`);
    console.log("PASS mobile package layout without horizontal overflow");
    console.log("All browser learning-flow tests passed.");
  }finally{
    for(const ctx of contexts)await ctx.close();await browser.close();
    if(ids.length){await db.delete(sessions).where(inArray(sessions.userId,ids));await db.delete(lessons).where(inArray(lessons.studentId,ids));await db.delete(lessonPackages).where(inArray(lessonPackages.studentId,ids));await db.delete(transactions).where(inArray(transactions.userId,ids));await db.delete(teacherProfiles).where(inArray(teacherProfiles.userId,ids));await db.delete(users).where(inArray(users.id,ids));}await pool.end();
  }
}
run().catch(e=>{console.error(e);process.exitCode=1;});
